use std::sync::atomic::{AtomicU8, Ordering};

/// Supported UI languages for Testrix.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub(crate) enum AppLanguage {
    En = 0,
    Fr = 1,
    De = 2,
    Es = 3,
    It = 4,
    Pt = 5,
    Ru = 6,
    Ar = 7,
    Tr = 8,
    Ja = 9,
    Ko = 10,
    ZhCn = 11,
    ZhTw = 12,
}

impl AppLanguage {
    pub const ALL: [Self; 13] = [
        Self::En,
        Self::Fr,
        Self::De,
        Self::Es,
        Self::It,
        Self::Pt,
        Self::Ru,
        Self::Ar,
        Self::Tr,
        Self::Ja,
        Self::Ko,
        Self::ZhCn,
        Self::ZhTw,
    ];

    pub const fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Fr => "fr",
            Self::De => "de",
            Self::Es => "es",
            Self::It => "it",
            Self::Pt => "pt",
            Self::Ru => "ru",
            Self::Ar => "ar",
            Self::Tr => "tr",
            Self::Ja => "ja",
            Self::Ko => "ko",
            Self::ZhCn => "zh-CN",
            Self::ZhTw => "zh-TW",
        }
    }

    pub const fn native_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Fr => "Français",
            Self::De => "Deutsch",
            Self::Es => "Español",
            Self::It => "Italiano",
            Self::Pt => "Português",
            Self::Ru => "Русский",
            Self::Ar => "اللغة العربية",
            Self::Tr => "Türkçe",
            Self::Ja => "日本語",
            Self::Ko => "한국어",
            Self::ZhCn => "简体中文",
            Self::ZhTw => "繁體中文",
        }
    }

    pub fn from_code(code: &str) -> Self {
        let normalized = code.trim().to_ascii_lowercase();
        match normalized.as_str() {
            "fr" => Self::Fr,
            "de" => Self::De,
            "es" => Self::Es,
            "it" => Self::It,
            "pt" | "pt-br" | "pt-pt" => Self::Pt,
            "ru" => Self::Ru,
            "ar" => Self::Ar,
            "tr" => Self::Tr,
            "ja" => Self::Ja,
            "ko" => Self::Ko,
            "zh-cn" | "zh_cn" | "zh-hans" | "zh" => Self::ZhCn,
            "zh-tw" | "zh_tw" | "zh-hk" | "zh-hant" => Self::ZhTw,
            _ => Self::En,
        }
    }

    fn from_u8(v: u8) -> Self {
        Self::ALL.get(v as usize).copied().unwrap_or(Self::En)
    }
}

static CURRENT_LANG: AtomicU8 = AtomicU8::new(AppLanguage::En as u8);

pub(crate) fn current_language() -> AppLanguage {
    AppLanguage::from_u8(CURRENT_LANG.load(Ordering::Relaxed))
}

pub(crate) fn set_language(lang: AppLanguage) {
    CURRENT_LANG.store(lang as u8, Ordering::Relaxed);
}

/// Looks up the localized string for `key` in the active [`AppLanguage`].
pub(crate) fn t(key: &str) -> &'static str {
    tr(current_language(), key)
}

/// Looks up the localized string for `key` in `lang`, falling back to English.
pub(crate) fn tr(lang: AppLanguage, key: &str) -> &'static str {
    let translated = match lang {
        AppLanguage::En => tr_en(key),
        AppLanguage::Fr => tr_fr(key),
        AppLanguage::De => tr_de(key),
        AppLanguage::Es => tr_es(key),
        AppLanguage::It => tr_it(key),
        AppLanguage::Pt => tr_pt(key),
        AppLanguage::Ru => tr_ru(key),
        AppLanguage::Ar => tr_ar(key),
        AppLanguage::Tr => tr_tr(key),
        AppLanguage::Ja => tr_ja(key),
        AppLanguage::Ko => tr_ko(key),
        AppLanguage::ZhCn => tr_zh_cn(key),
        AppLanguage::ZhTw => tr_zh_tw(key),
    };
    translated.unwrap_or_else(|| tr_en(key).unwrap_or("?"))
}

